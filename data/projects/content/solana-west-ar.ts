function allArabicProjectFaqs(): readonly FaqPair[] {
  return SOLANA_WEST_AR_FAQ_GROUPS.flatMap((g) => g.items).map((item) => ({
    question: item.question,
    answer: `${item.aiSnippet}\n\n${item.answer}`,
  }));
}

